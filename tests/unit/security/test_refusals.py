"""Packets the firewall refused: counted by the host unit, read and judged (ADR-0028 T3b)."""

from __future__ import annotations

import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

from aistack import firewall_snapshot as snapshot
from aistack.security.definition import SecurityDefinition
from aistack.security.findings import INFORMATION, WATCH
from aistack.security.refusals import Sample, assess_refusals, read_refusals, window_counts
from aistack.security.firewall import parse_table

NOW = datetime(2026, 11, 20, 12, 0, tzinfo=timezone.utc)

SAVE = """# Generated by iptables-save
*nat
:PREROUTING ACCEPT [9:9]
[99:99] -A POSTROUTING -j DROP
COMMIT
*filter
:INPUT DROP [40:2400]
:FORWARD DROP [0:0]
:DOCKER-USER - [0:0]
[7:420] -A DOCKER-USER -i enp0s31f6 -m conntrack --ctstate NEW -j LOG --log-prefix "DOCKER-USER-REFUSE "
[5:300] -A DOCKER-USER -i enp0s31f6 -j DROP
[3:180] -A ufw-user-input -p tcp --dport 22 -j DROP
[2:120] -A ufw6-after-input -j REJECT --reject-with icmp6-port-unreachable
[1:60] -A DOCKER -i docker0 -j DROP
[50:3000] -A INPUT -j ACCEPT
COMMIT
"""


def _sample(minutes_ago: float, boot: str = "b1", **drops: int) -> Sample:
    return Sample(NOW - timedelta(minutes=minutes_ago), boot, {"docker_user": 0, "input_policy": 0, "ufw": 0, "other": 0, **drops})


def test_the_unit_counts_what_each_family_of_rules_refused_and_only_in_the_filter_table() -> None:
    assert snapshot.refusals(SAVE) == {"docker_user": 5, "input_policy": 40, "ufw": 5, "other": 1}


def test_the_text_files_keep_the_form_the_reader_of_the_rules_always_saw() -> None:
    stripped = snapshot.strip_counters(SAVE)

    assert "[5:300]" not in stripped and ":INPUT DROP [0:0]" in stripped
    table = parse_table(stripped)
    assert table.policies["INPUT"] == "DROP"
    assert any(rule.chain == "DOCKER-USER" and rule.target == "DROP" for rule in table.rules)


def test_a_run_appends_a_line_and_keeps_seven_days(tmp_path: Path, monkeypatch) -> None:
    import subprocess
    import sys

    monkeypatch.setattr(snapshot.subprocess, "run", lambda command, **_: subprocess.CompletedProcess(command, 0, stdout=SAVE))
    monkeypatch.setattr(snapshot.os, "chown", lambda *_: None)
    old = (datetime.now(timezone.utc) - timedelta(days=8)).isoformat(timespec="seconds")
    recent = (datetime.now(timezone.utc) - timedelta(days=1)).isoformat(timespec="seconds")
    (tmp_path / snapshot.REFUSALS).write_text(
        json.dumps({"at": old, "boot": "x", "drops": {}}) + "\n" + json.dumps({"at": recent, "boot": "x", "drops": {}}) + "\nnot json\n",
        encoding="utf-8",
    )
    monkeypatch.setattr(sys, "argv", ["aistack-firewall-snapshot", "--output", str(tmp_path)])

    assert snapshot.main() == 0

    lines = [json.loads(line) for line in (tmp_path / snapshot.REFUSALS).read_text(encoding="utf-8").splitlines()]
    assert [line["at"] for line in lines][0] == recent and len(lines) == 2
    assert lines[-1]["drops"] == {"docker_user": 10, "input_policy": 80, "ufw": 10, "other": 2}


def test_a_failed_ipv4_answer_appends_nothing(tmp_path: Path, monkeypatch) -> None:
    import subprocess
    import sys

    monkeypatch.setattr(snapshot.subprocess, "run", lambda command, **_: subprocess.CompletedProcess(command, 1, stdout=""))
    monkeypatch.setattr(snapshot.os, "chown", lambda *_: None)
    monkeypatch.setattr(sys, "argv", ["aistack-firewall-snapshot", "--output", str(tmp_path)])

    assert snapshot.main() == 1
    assert not (tmp_path / snapshot.REFUSALS).exists()


def test_the_window_counts_the_difference_between_readings() -> None:
    samples = [_sample(300, docker_user=100), _sample(200, docker_user=130), _sample(10, docker_user=190, ufw=4)]

    counts, covered = window_counts(samples, NOW - timedelta(hours=24))

    assert counts["docker_user"] == 90 and counts["ufw"] == 4
    assert covered == timedelta(minutes=290)


def test_the_sample_before_the_window_anchors_the_first_interval() -> None:
    samples = [_sample(25 * 60, docker_user=10), _sample(60, docker_user=70), _sample(10, docker_user=75)]

    counts, _ = window_counts(samples, NOW - timedelta(hours=24))

    assert counts["docker_user"] == 65


def test_a_reboot_or_a_counter_that_goes_down_restarts_from_zero_never_negative() -> None:
    samples = [_sample(300, "b1", docker_user=500), _sample(200, "b2", docker_user=20), _sample(100, "b2", docker_user=5)]

    counts, _ = window_counts(samples, NOW - timedelta(hours=24))

    assert counts["docker_user"] == 20 + 5


def test_the_summary_says_how_many_never_who_and_stays_information_by_default() -> None:
    samples = [_sample(300, docker_user=0), _sample(5, docker_user=900, input_policy=100)]

    findings = assess_refusals(samples, NOW, SecurityDefinition())

    assert [finding.key for finding in findings] == ["refusals.summary"]
    assert findings[0].severity == INFORMATION and "1000 packet(s)" in findings[0].title
    assert any("900 from outside the LAN and the VPN" in line for line in findings[0].evidence)
    assert "address" in findings[0].unknown


def test_a_sustained_rate_over_the_threshold_is_to_watch_a_short_burst_is_not() -> None:
    definition = SecurityDefinition(refusal_watch_per_hour=100)
    sustained = [_sample(300, docker_user=0), _sample(5, docker_user=1000)]
    burst = [_sample(20, docker_user=0), _sample(5, docker_user=1000)]

    assert [finding.key for finding in assess_refusals(sustained, NOW, definition)] == ["refusals.summary", "refusals.high"]
    assert assess_refusals(sustained, NOW, definition)[1].severity == WATCH
    assert [finding.key for finding in assess_refusals(burst, NOW, definition)] == ["refusals.summary"]


def test_no_history_an_old_one_and_a_first_reading_are_findings_about_the_source() -> None:
    definition = SecurityDefinition()

    assert [item.key for item in assess_refusals(None, NOW, definition)] == ["refusals.unread"]
    assert [item.key for item in assess_refusals([_sample(600)], NOW, definition)] == ["refusals.unread"]
    assert [item.key for item in assess_refusals([_sample(5)], NOW, definition)] == ["refusals.started"]


def test_the_reader_skips_lines_it_cannot_read(tmp_path: Path) -> None:
    (tmp_path / "firewall-refusals.jsonl").write_text(
        "garbage\n" + json.dumps({"at": NOW.isoformat(), "boot": "b", "drops": {"ufw": 3}}) + "\n" + json.dumps({"at": "x"}) + "\n",
        encoding="utf-8",
    )

    samples = read_refusals(tmp_path)

    assert samples is not None and len(samples) == 1 and samples[0].drops == {"ufw": 3}
    assert read_refusals(tmp_path / "nothing") is None


def test_without_the_host_unit_the_report_already_says_so_and_this_adds_nothing() -> None:
    assert assess_refusals(None, NOW, SecurityDefinition(), snapshot_present=False) == []
