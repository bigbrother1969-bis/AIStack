"""
Project Docker events into the graph.

Separate from `project_observation_history`: a batch is a
`since`/`until` window of events, each with its own subject, not one
subject's snapshot. Batches live under `generated_dir / "docker-events"`
(see `aistack.providers.docker.events_history`), which the generic walk
never finds, so no batch is projected twice.

Does not clear the store; runs in the same rebuild pass as
`project_observation_history`.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

from aistack.history import format_instant, latest_observations
from aistack.timemachine.graph import GraphStore, Literal
from aistack.timemachine.iri import docker_event_iri, stream_iri
from aistack.timemachine.projection.filter import filter_fact
from aistack.timemachine.vocabulary import (
    AISTACK_DOCKER_ACTION,
    AISTACK_OCCURRED_AT,
    AISTACK_STABLE_SUBJECT,
    PROV_ACTIVITY,
    PROV_ENTITY,
    PROV_GENERATED_AT_TIME,
    PROV_WAS_GENERATED_BY,
    RDF_TYPE,
    XSD_DATE_TIME,
)

# Stem written by `aistack.providers.docker.events_history`, redeclared
# rather than imported across the writer/reader boundary.
STEM = "docker-events"


@dataclass(frozen=True)
class DockerEventsProjectionSummary:
    """What one `project_docker_events` run did."""

    batches_seen: int
    events_seen: int
    facts_written: int
    facts_dropped: int


def project_docker_events(
    store: GraphStore,
    generated_dir: Path = Path("reports/generated"),
    user_data_roots: Iterable[str] = (),
) -> DockerEventsProjectionSummary:
    """
    Add every recorded Docker-events batch under
    `generated_dir / "docker-events"` to `store`.

    All events are generated by one `prov:Activity`
    (`stream_iri("docker-events")`). Per event: a `prov:Entity` with
    `prov:generatedAtTime` (the batch's recording instant),
    `aistack:occurredAt` (Docker's own time), `aistack:stableSubject`
    (computed by the collector) and `aistack:dockerAction`.

    `aistack:clockSource` (`ADR-0011` § 5) is not written: the
    collector runs on one host, so there is no clock drift to state.
    Every fact goes through `filter_fact`.
    """

    docker_events_dir = generated_dir / "docker-events"
    activity = stream_iri(STEM)

    batches_seen = 0
    events_seen = 0
    facts_written = 0
    facts_dropped = 0

    def emit(subject: str, predicate: str, obj: str | Literal) -> None:
        nonlocal facts_written, facts_dropped
        if filter_fact(subject, obj, user_data_roots):
            store.add(subject, predicate, obj)
            facts_written += 1
        else:
            facts_dropped += 1

    for observation in latest_observations(docker_events_dir, STEM):
        instant = observation.observed_at

        if batches_seen == 0:
            # Only once data is found: no Activity for a collector
            # that never ran.
            emit(activity, RDF_TYPE, PROV_ACTIVITY)

        batches_seen += 1
        parsed = json.loads(observation.read())
        events = parsed.get("events") if isinstance(parsed, dict) else None
        if not isinstance(events, list):
            continue

        instant_label = format_instant(instant)

        for index, event in enumerate(events):
            if not isinstance(event, dict):
                continue

            events_seen += 1
            entity = docker_event_iri(instant_label, index)

            emit(entity, RDF_TYPE, PROV_ENTITY)
            emit(entity, PROV_WAS_GENERATED_BY, activity)
            emit(
                entity,
                PROV_GENERATED_AT_TIME,
                Literal(instant.isoformat(), datatype=XSD_DATE_TIME),
            )

            occurred_at = event.get("occurred_at")
            if isinstance(occurred_at, str):
                emit(
                    entity,
                    AISTACK_OCCURRED_AT,
                    Literal(occurred_at, datatype=XSD_DATE_TIME),
                )

            subject = event.get("subject")
            if isinstance(subject, str):
                emit(entity, AISTACK_STABLE_SUBJECT, Literal(subject))

            action = event.get("action")
            if isinstance(action, str) and action:
                emit(entity, AISTACK_DOCKER_ACTION, Literal(action))

    return DockerEventsProjectionSummary(
        batches_seen=batches_seen,
        events_seen=events_seen,
        facts_written=facts_written,
        facts_dropped=facts_dropped,
    )
