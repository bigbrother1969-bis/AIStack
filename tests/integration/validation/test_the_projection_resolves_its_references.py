import re

from aistack.integrity.checks.reference_integrity import (
    ReferenceIntegrityCheck,
)


INDEX = "FDN-0001"

KEPT_AT_THE_TAG = "## Kept at the tag"

DOCUMENT = re.compile(r"[A-Z]+-\d{4}")


def kept_at_the_tag(projection) -> set[str]:
    """
    The documents `FDN-0001` declares kept at the tag, read from the
    projection and not from a copy held here: the table is the one
    place that says so, and a list repeated in a test would be a
    second place.
    """

    index = next(
        (a for a in projection.artifacts if a.id == INDEX), None
    )

    assert index is not None, f"the projection does not carry {INDEX}"

    _, found, section = index.content.partition(KEPT_AT_THE_TAG)
    section = section.split("\n## ", 1)[0] if found else ""

    cells = (
        line.split("|")[1].strip()
        for line in section.splitlines()
        if line.startswith("|")
    )

    return {cell for cell in cells if DOCUMENT.fullmatch(cell)}


def unresolved(projection) -> set[str]:
    """The artifacts a declared reference designates and the bundle lacks."""

    return {
        subject.split("→")[1].strip()
        for finding in ReferenceIntegrityCheck().evaluate(projection)
        for subject in finding.subjects
    }


def test_the_published_heritage_resolves_every_reference(projection):
    """
    Every `relations: references:` in this repository designates
    an artifact this repository declares, or a document `FDN-0001`
    declares kept at the tag.

    The projection is regenerated by the `projection` fixture,
    and that is the point — see its docstring for the defect that
    put it there, and for the `if not exists: return` that let an
    earlier version pass while verifying nothing.

    **What changed on 2026-11-18, `GOV-0002/OS-095`.** The test
    asserted that the check reported nothing. On `main` it reports
    twelve references — to `FDN-0005`, `FDN-0006`, `GOV-0001`,
    `OPS-0012`, `STD-0001`, `STD-0101` and `STD-0200` — documents
    that stayed at the tag by the owner's decision of 2026-11-15.
    The check publishes them as an observation, which is right: they
    are real. This test asserts the other half: that none leads
    anywhere the heritage has not said it leads. A reference to a
    document that is neither in `main` nor in that table fails here.
    """

    designated = unresolved(projection)
    kept = kept_at_the_tag(projection)

    assert designated <= kept, sorted(designated - kept)


def test_the_table_is_read_and_not_merely_parsed(projection):
    """
    The test above passes on a table nobody could read only if the
    check reports nothing: no unresolved reference, nothing to
    excuse. So the figures are stated, measured 2026-11-18 on
    `main`: the table lists eleven documents, and the check reports
    twelve references to seven of them. Floors, not equalities.

    And no document of the table is an artifact of the projection:
    a document that came back to `main` and stayed listed would
    excuse a reference it no longer needs to.
    """

    kept = kept_at_the_tag(projection)

    assert len(kept) >= 11
    assert len(unresolved(projection)) >= 1

    held = {artifact.id for artifact in projection.artifacts}

    assert kept & held == set(), sorted(kept & held)
